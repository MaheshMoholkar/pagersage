"""Write docs/cypher.md: every query in backend/queries/ with what it answers, the FalkorDB
algorithm or index it uses, and the Python function that runs it (task G19).

Run from backend/: `uv run python ../scripts/cypher_catalogue.py` (or `make catalogue`).
`tests/test_cypher_catalogue.py` fails when docs/cypher.md is stale.
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QUERIES = ROOT / "backend" / "queries"
CODE = ROOT / "backend" / "pagersage"
OUT = ROOT / "docs" / "cypher.md"

# "T3 suspect_changes: ...", "Seed (G03): ...", "Batch (G05): ...", "G17 replay_incident: ..."
_TAG = re.compile(r"^(T\d+[a-z]?\s+\w+|(Seed|Batch|Live weights) \(G\d+\)|G\d+[\w ]*?)\s*:\s*")
_ALGOS = [
    (re.compile(r"algo\.(\w+)", re.I), "`algo.{}`"),
    (re.compile(r"db\.idx\.vector\.queryNodes", re.I), "vector index"),
    (re.compile(r"db\.idx\.fulltext\.queryNodes", re.I), "full-text index"),
]
SECTIONS = [
    ("Agent tools", lambda n: not n.startswith(("seed_", "count_", "batch_"))),
    ("Batch algorithms", lambda n: n.startswith("batch_")),
    ("Seed loader", lambda n: n.startswith(("seed_", "count_"))),
]
_BATCH_READS = {"ownership_gaps", "real_teams"}  # batch results read back, listed with batch


def summary(text: str) -> str:
    """First sentence of the // header, without its task tag."""
    lines = []
    for line in text.splitlines():
        if not line.startswith("//"):
            break
        body = line[2:].strip()
        if body.startswith(("Params:", "Returns")):
            break
        lines.append(body)
    header = _TAG.sub("", " ".join(lines), count=1)
    first = re.split(r"(?<=[.?!])\s", header, maxsplit=1)[0]
    return first[0].upper() + first[1:] if first else ""


def algorithms(text: str) -> str:
    body = "\n".join(line for line in text.splitlines() if not line.startswith("//"))
    found = []
    for pattern, label in _ALGOS:
        for m in pattern.finditer(body):
            name = label.format(*m.groups())
            if name not in found:
                found.append(name)
    return ", ".join(found)


def callers(names: set[str]) -> dict[str, list[str]]:
    """Query name -> functions that name it, as module.function: queries.load("<name>") calls,
    and string constants such as the seed loader's ("seed_services", rows) pairs."""
    used: dict[str, list[str]] = {}
    for path in sorted(CODE.rglob("*.py")):
        module = path.relative_to(CODE).with_suffix("").as_posix().rsplit("/", 1)[-1]
        for fn in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if not isinstance(fn, ast.FunctionDef):
                continue
            for node in ast.walk(fn):
                if isinstance(node, ast.Constant) and node.value in names:
                    entry = f"`{module}.{fn.name}`"
                    found = used.setdefault(node.value, [])
                    if entry not in found:
                        found.append(entry)
    return used


def render() -> str:
    files = sorted(QUERIES.glob("*.cypher"))
    used = callers({f.stem for f in files})
    out = [
        "# Cypher catalogue",
        "",
        "Every query PagerSage runs, one statement per file in "
        "[`backend/queries/`](../backend/queries/). Generated by "
        "`scripts/cypher_catalogue.py` (`make catalogue`) from each file's `//` header; "
        "don't edit by hand.",
        "",
    ]
    for title, belongs in SECTIONS:
        rows = [
            f
            for f in files
            if (f.stem in _BATCH_READS and title == "Batch algorithms")
            or (f.stem not in _BATCH_READS and belongs(f.stem))
        ]
        out += [
            f"## {title} ({len(rows)})",
            "",
            "| Query | What it answers | Algorithm / index | Run by |",
            "|---|---|---|---|",
        ]
        for f in rows:
            text = f.read_text(encoding="utf-8")
            link = f"[`{f.stem}`](../backend/queries/{f.name})"
            run_by = ", ".join(used.get(f.stem, []))
            out.append(f"| {link} | {summary(text)} | {algorithms(text)} | {run_by} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
